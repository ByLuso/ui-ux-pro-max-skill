export function findSpeciesByScientificName(name: string): Species | null {
  const normalized = name.trim().toLowerCase();
  return (
    SPECIES.find((s) => {
      const parts = s.scientificName.toLowerCase().split(" ");
      const candidate = normalized.split(" ").slice(0, parts.length).join(" ");
      return s.scientificName.toLowerCase() === candidate;
    }) ?? null
  );
}

export function speciesForRegion(regionId: string): Species[] {
  return SPECIES.filter((s) => s.regions.includes(regionId));
}
